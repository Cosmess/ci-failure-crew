using System.Diagnostics;
using System.Diagnostics.Metrics;

namespace CiFailureCrew.Core.Telemetry;

/// <summary>
/// OpenTelemetry instrumentation of the crew. Spans follow the GenAI semantic conventions
/// (<c>invoke_agent</c>) so tools like the Aspire dashboard group them by agent.
/// </summary>
public static class CrewTelemetry
{
    public const string SourceName = "CiFailureCrew";

    public static readonly ActivitySource ActivitySource = new(SourceName);

    private static readonly Meter Meter = new(SourceName);

    public static readonly Counter<long> InputTokens = Meter.CreateCounter<long>("cfc.tokens.input", "{token}", "Input tokens sent to the models.");
    public static readonly Counter<long> OutputTokens = Meter.CreateCounter<long>("cfc.tokens.output", "{token}", "Output tokens generated by the models.");
    public static readonly Counter<long> Diagnoses = Meter.CreateCounter<long>("cfc.diagnoses", "{job}", "Failed jobs diagnosed, by category and source (agents or a known rule).");
    public static readonly Counter<long> AgentFailures = Meter.CreateCounter<long>("cfc.agent.failures", "{failure}", "Agent calls that failed after every retry.");
    public static readonly Histogram<double> AgentDuration = Meter.CreateHistogram<double>("cfc.agent.duration", "s", "Duration of each agent call.");

    public static Activity? StartExplanation(int jobs)
    {
        var activity = ActivitySource.StartActivity("explain_failure");
        activity?.SetTag("cfc.jobs", jobs);
        return activity;
    }

    public static Activity? StartAgent(string agentName, string job)
    {
        var activity = ActivitySource.StartActivity($"invoke_agent {agentName}");
        activity?.SetTag("gen_ai.operation.name", "invoke_agent");
        activity?.SetTag("gen_ai.agent.name", agentName);
        activity?.SetTag("cfc.job", job);
        return activity;
    }

    public static void RecordError(Activity? activity, Exception exception)
    {
        activity?.SetStatus(ActivityStatusCode.Error, exception.Message);
        activity?.AddException(exception);
    }
}
